# 12. SE BLOCK
# ============================================================

class SEBlock(
    layers.Layer
):

    def __init__(
        self,
        reduction=16,
        **kwargs
    ):

        super().__init__(
            **kwargs
        )

        self.reduction = reduction


    def build(
        self,
        input_shape
    ):

        channels = int(
            input_shape[-1]
        )

        reduced = max(
            channels // self.reduction,
            1
        )

        self.pool = (
            layers.GlobalAveragePooling2D()
        )

        self.fc1 = layers.Dense(
            reduced,
            activation="relu"
        )

        self.fc2 = layers.Dense(
            channels,
            activation="sigmoid"
        )

        self.reshape = layers.Reshape(
            (
                1,
                1,
                channels
            )
        )

        super().build(
            input_shape
        )


    def call(
        self,
        inputs
    ):

        x = self.pool(
            inputs
        )

        x = self.fc1(
            x
        )

        x = self.fc2(
            x
        )

        x = self.reshape(
            x
        )

        return inputs * x


