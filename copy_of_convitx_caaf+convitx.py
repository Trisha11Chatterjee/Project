# Cross-Attention Adaptive Feature Fusion
# ============================================================

class CrossAttentionAdaptiveFeatureFusion(
    layers.Layer
):

    def __init__(

        self,

        projection_dim=256,

        num_heads=8,

        dropout=0.1,

        **kwargs

    ):

        super().__init__(
            **kwargs
        )

        self.projection_dim = (
            projection_dim
        )


        # ----------------------------------------------------
        # Normalization
        # ----------------------------------------------------

        self.cnn_norm = (
            layers.LayerNormalization(
                epsilon=1e-6
            )
        )

        self.vit_norm = (
            layers.LayerNormalization(
                epsilon=1e-6
            )
        )


        # ----------------------------------------------------
        # CNN → ViT attention
        # ----------------------------------------------------

        self.cnn_to_vit = (

            layers.MultiHeadAttention(

                num_heads=num_heads,

                key_dim=(
                    projection_dim
                    // num_heads
                ),

                dropout=dropout,

                name="cnn_to_vit_attention"

            )

        )


        # ----------------------------------------------------
        # ViT → CNN attention
        # ----------------------------------------------------

        self.vit_to_cnn = (

            layers.MultiHeadAttention(

                num_heads=num_heads,

                key_dim=(
                    projection_dim
                    // num_heads
                ),

                dropout=dropout,

                name="vit_to_cnn_attention"

            )

        )


        # ----------------------------------------------------
        # Adaptive gate
        # ----------------------------------------------------

        self.gate_dense1 = layers.Dense(

            projection_dim,

            activation="relu"

        )


        self.gate_dense2 = layers.Dense(

            2,

            activation="softmax"

        )


        # ----------------------------------------------------
        # Output projection
        # ----------------------------------------------------

        self.output_projection = (
            layers.Dense(
                projection_dim,
                activation="relu"
            )
        )


    def call(

        self,

        inputs

    ):

        cnn_feature, vit_feature = (
            inputs
        )


        # ----------------------------------------------------
        # Convert feature vectors to tokens
        # ----------------------------------------------------

        cnn_tokens = tf.expand_dims(

            cnn_feature,

            axis=1

        )


        vit_tokens = tf.expand_dims(

            vit_feature,

            axis=1

        )


        # ----------------------------------------------------
        # Normalize
        # ----------------------------------------------------

        cnn_norm = self.cnn_norm(
            cnn_tokens
        )

        vit_norm = self.vit_norm(
            vit_tokens
        )


        # ----------------------------------------------------
        # CNN → ViT Cross Attention
        # ----------------------------------------------------

        cnn_attention = (

            self.cnn_to_vit(

                query=cnn_norm,

                key=vit_norm,

                value=vit_norm

            )

        )


        cnn_fused = (

            cnn_tokens

            +

            cnn_attention

        )


        # ----------------------------------------------------
        # ViT → CNN Cross Attention
        # ----------------------------------------------------

        vit_attention = (

            self.vit_to_cnn(

                query=vit_norm,

                key=cnn_norm,

                value=cnn_norm

            )

        )


        vit_fused = (

            vit_tokens

            +

            vit_attention

        )


        # ----------------------------------------------------
        # Remove sequence dimension
        # ----------------------------------------------------

        cnn_fused = tf.squeeze(

            cnn_fused,

            axis=1

        )


        vit_fused = tf.squeeze(

            vit_fused,

            axis=1

        )


        # ----------------------------------------------------
        # Adaptive gating
        # ----------------------------------------------------

        gate_input = tf.concat(

            [

                cnn_fused,

                vit_fused

            ],

            axis=-1

        )


        gate = self.gate_dense1(

            gate_input

        )


        gate = self.gate_dense2(

            gate

        )


        cnn_weight = gate[
            :,
            0:1
        ]


        vit_weight = gate[
            :,
            1:2
        ]


        # ----------------------------------------------------
        # Adaptive weighted fusion
        # ----------------------------------------------------

        fused = (

            cnn_weight
            * cnn_fused

            +

            vit_weight
            * vit_fused

        )


        # ----------------------------------------------------
        # Final projection
        # ----------------------------------------------------

        fused = self.output_projection(
            fused
        )


        return fused


