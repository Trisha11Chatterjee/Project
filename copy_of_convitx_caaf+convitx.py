# 20. CAAF
# ============================================================

class CAAF(
    layers.Layer
):

    def __init__(
        self,
        projection_dim=256,
        num_heads=8,
        dropout=0.1,
        **kwargs
    ):

        super().__init__(
            **kwargs
        )


        self.cnn_norm = (
            layers.LayerNormalization(
                epsilon=1e-6
            )
        )


        self.vit_norm = (
            layers.LayerNormalization(
                epsilon=1e-6
            )
        )


        # CNN queries ViT

        self.cnn_to_vit = (
            layers.MultiHeadAttention(

                num_heads=num_heads,

                key_dim=(
                    projection_dim
                    // num_heads
                ),

                dropout=dropout

            )
        )


        # ViT queries CNN

        self.vit_to_cnn = (
            layers.MultiHeadAttention(

                num_heads=num_heads,

                key_dim=(
                    projection_dim
                    // num_heads
                ),

                dropout=dropout

            )
        )


        self.cnn_gate = layers.Dense(
            1
        )


        self.vit_gate = layers.Dense(
            1
        )


        self.output_projection = (
            layers.Dense(
                projection_dim,
                activation="relu"
            )
        )


    def call(
        self,
        inputs
    ):

        cnn_tokens, vit_tokens = inputs


        # ----------------------------------------------------
        # NORMALIZE
        # ----------------------------------------------------

        cnn_norm = self.cnn_norm(
            cnn_tokens
        )

        vit_norm = self.vit_norm(
            vit_tokens
        )


        # ----------------------------------------------------
        # CNN → ViT
        # ----------------------------------------------------

        cnn_attention = (

            self.cnn_to_vit(

                query=cnn_norm,

                key=vit_norm,

                value=vit_norm

            )

        )


        cnn_fused = (

            cnn_tokens

            +

            cnn_attention

        )


        # ----------------------------------------------------
        # ViT → CNN
        # ----------------------------------------------------

        vit_attention = (

            self.vit_to_cnn(

                query=vit_norm,

                key=cnn_norm,

                value=cnn_norm

            )

        )


        vit_fused = (

            vit_tokens

            +

            vit_attention

        )


        # ----------------------------------------------------
        # GLOBAL FEATURES
        # ----------------------------------------------------

        cnn_global = (
            tf.reduce_mean(
                cnn_fused,
                axis=1
            )
        )


        vit_global = (
            tf.reduce_mean(
                vit_fused,
                axis=1
            )
        )


        # ----------------------------------------------------
        # ADAPTIVE GATING
        # ----------------------------------------------------

        cnn_score = self.cnn_gate(
            cnn_global
        )


        vit_score = self.vit_gate(
            vit_global
        )


        scores = tf.concat(

            [
                cnn_score,
                vit_score
            ],

            axis=-1

        )


        weights = tf.nn.softmax(
            scores,
            axis=-1
        )


        cnn_weight = weights[
            :,
            0:1
        ]


        vit_weight = weights[
            :,
            1:2
        ]


        # ----------------------------------------------------
        # ADAPTIVE FUSION
        # ----------------------------------------------------

        fused = (

            cnn_weight
            * cnn_global

            +

            vit_weight
            * vit_global

        )


        fused = self.output_projection(
            fused
        )


        return fused


