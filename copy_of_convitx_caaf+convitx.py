    for i, name in enumerate(class_names):

        print(
            f"{name:30s}",
            end=""
        )

        for j in range(num_classes):

            print(
                f"{cm_percent[i,j]:17.2f}%",
                end=""
            )

        print()


    # --------------------------------------------------------
    # CLASSIFICATION REPORT
    # --------------------------------------------------------

    print("\n")
    print("CLASSIFICATION REPORT")
    print("-" * 70)

    print(
        classification_report(
            y_true,
            y_pred,
            labels=all_labels,
            target_names=class_names,
            digits=4,
            zero_division=0
        )
    )


    # --------------------------------------------------------
    # OVERALL ACCURACY
    # --------------------------------------------------------

    accuracy = (
        np.trace(cm)
        /
        np.sum(cm)
        if np.sum(cm) > 0
        else 0
    )

    print(
        f"Overall Accuracy: "
        f"{accuracy * 100:.2f}%"
    )


