# ============================================================
# 27. KL DIVERGENCE
# ============================================================

def kl_divergence(

    p,

    q

):

    p = torch.clamp(

        p,

        min=EPSILON

    )


    q = torch.clamp(

        q,

        min=EPSILON

    )


    return torch.mean(

        torch.sum(

            p *

            torch.log(

                p / q

            ),

            dim=1

        )

    )


# ============================================================
# 28. JS DIVERGENCE
# ============================================================

def js_divergence(

    p,

    q

):

    m = 0.5 * (

        p + q

    )


    return (

        0.5 *

        (

            kl_divergence(

                p,

                m

            )

            +

            kl_divergence(

                q,

                m

            )

        )

    )


# ============================================================
# 29. ENTROPY REGULARIZATION
# ============================================================

def entropy_regularization(

    p

):

    p = torch.clamp(

        p,

        min=EPSILON

    )


    entropy = -torch.sum(

        p *

        torch.log(p),

        dim=1

    )


    return -torch.mean(

        entropy

    )


