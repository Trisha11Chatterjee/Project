def train_one_epoch():

    model.train()


    running_loss = 0.0

    running_correct = 0

    running_total = 0


    progress = tqdm(

        train_loader,

        desc="Training",

        leave=True

    )


    for (

        rgb,

        depth,

        synthetic,

        labels

    ) in progress:


        # ====================================================
        # GPU TRANSFER
        # ====================================================

        rgb = rgb.to(

            DEVICE,

            non_blocking=True

        )


        depth = depth.to(

            DEVICE,

            non_blocking=True

        )


        synthetic = synthetic.to(

            DEVICE,

            non_blocking=True

        )


        labels = labels.to(

            DEVICE,

            non_blocking=True

        )


        optimizer.zero_grad(

            set_to_none=True

        )


        # ====================================================
        # FIRST FORWARD PASS
        #
        # Used to determine task sensitivity.
        # ====================================================

        with torch.autocast(

            device_type=DEVICE.type,

            dtype=torch.float16,

            enabled=USE_AMP

        ):

            first_output = model(

                rgb,

                depth,

                synthetic,

                sensitivity=None

            )


            first_logits = first_output[
                "logits"
            ]


            first_loss = classification_loss(

                first_logits,

                labels

            )


        # ====================================================
        # TASK SENSITIVITY
        # ====================================================

        features = first_output[
            "features"
        ]


        if USE_AMP:

            scaled_loss = (

                scaler.scale(
                    first_loss
                )

            )


            gradients = torch.autograd.grad(

                scaled_loss,

                features,

                retain_graph=True,

                create_graph=False,

                allow_unused=True

            )[0]


            if gradients is not None:

                gradients = (

                    gradients

                    /

                    scaler.get_scale()

                )

        else:

            gradients = torch.autograd.grad(

                first_loss,

                features,

                retain_graph=True,

                create_graph=False,

                allow_unused=True

            )[0]


        if gradients is None:

            sensitivity = torch.ones(

                features.shape[0],

                features.shape[2],

                device=DEVICE

            )

        else:

            sensitivity = torch.sqrt(

                torch.mean(

                    gradients.detach() ** 2,

                    dim=1

                )

                +

                EPSILON

            )


        # ====================================================
        # SECOND FORWARD PASS
        #
        # FESR redistribution
        # ====================================================

        with torch.autocast(

            device_type=DEVICE.type,

            dtype=torch.float16,

            enabled=USE_AMP

        ):

            output = model(

                rgb,

                depth,

                synthetic,

                sensitivity=sensitivity

            )


            logits = output[
                "logits"
            ]


            # --------------------------------------------
            # Classification loss
            # --------------------------------------------

            loss_cls = classification_loss(

                logits,

                labels

            )


            # --------------------------------------------
            # Energy redistribution loss
            # --------------------------------------------

            energy = output[

                "energy_distribution"

            ]


            target = output[

                "target_distribution"

            ]


            loss_red = kl_divergence(

                target,

                energy

            )


            # --------------------------------------------
            # Synthetic consistency
            # --------------------------------------------

            synthetic_features = output[

                "synthetic_features"

            ]


            synthetic_energy = (

                model.calculate_energy_distribution(

                    synthetic_features

                )

            )


            loss_consistency = js_divergence(

                energy,

                synthetic_energy

            )


            # --------------------------------------------
            # Entropy
            # --------------------------------------------

            loss_entropy = entropy_regularization(

                target

            )


            # --------------------------------------------
            # TOTAL LOSS
            # --------------------------------------------

            loss = (

                loss_cls

                +

                LAMBDA_REDISTRIBUTION
                *
                loss_red

                +

                LAMBDA_CONSISTENCY
                *
                loss_consistency

                +

                LAMBDA_ENTROPY
                *
                loss_entropy

            )


        # ====================================================
        # BACKPROPAGATION
        # ====================================================

        if USE_AMP:

            scaler.scale(
                loss
            ).backward()


            scaler.unscale_(
                optimizer
            )


            torch.nn.utils.clip_grad_norm_(

                model.parameters(),

                1.0

            )


            scaler.step(
                optimizer
            )


            scaler.update()

        else:

            loss.backward()


            torch.nn.utils.clip_grad_norm_(

                model.parameters(),

                1.0

            )


            optimizer.step()


        # ====================================================
        # METRICS
        # ====================================================

        predictions = torch.argmax(

            logits,

            dim=1

        )


        correct = (

            predictions == labels

        ).sum().item()


        running_correct += correct

        running_total += labels.size(0)


        running_loss += (

            loss.item()

            *

            labels.size(0)

        )


        current_loss = (

            running_loss

            /

            running_total

        )


        current_accuracy = (

            running_correct

            /

            running_total

        )


        progress.set_postfix(

            loss=f"{current_loss:.4f}",

            accuracy=f"{current_accuracy:.4f}"

        )


    epoch_loss = (

        running_loss

        /

        running_total

    )


    epoch_accuracy = (

        running_correct

        /

        running_total

    )


    return (

        epoch_loss,

        epoch_accuracy

    )


