def train_one_epoch():

    model.train()


    total_loss = 0.0

    total_correct = 0

    total_samples = 0


    progress = tqdm(

        train_loader,

        desc="Training",

        leave=True

    )


    for (

        rgb,

        depth,

        synthetic,

        labels

    ) in progress:


        rgb = rgb.to(

            DEVICE,

            non_blocking=True

        )


        depth = depth.to(

            DEVICE,

            non_blocking=True

        )


        synthetic = synthetic.to(

            DEVICE,

            non_blocking=True

        )


        labels = labels.to(

            DEVICE,

            non_blocking=True

        )


        optimizer.zero_grad(

            set_to_none=True

        )


        # ====================================================
        # FIRST FORWARD PASS
        # ====================================================

        with torch.autocast(

            device_type=DEVICE.type,

            dtype=torch.float16,

            enabled=USE_AMP

        ):

            first_output = model(

                rgb,

                depth,

                synthetic,

                sensitivity=None

            )


            first_logits = (

                first_output["logits"]

            )


            first_loss = (

                classification_loss(

                    first_logits,

                    labels

                )

            )


        # ====================================================
        # TASK SENSITIVITY
        #
        # S_i =
        # sqrt(mean((dL/dF_i)^2))
        # ====================================================

        features = first_output[

            "features"

        ]


        if USE_AMP:

            scaled_loss = (

                scaler.scale(

                    first_loss

                )

            )


            gradients = torch.autograd.grad(

                scaled_loss,

                features,

                retain_graph=True,

                create_graph=False,

                allow_unused=True

            )[0]


            if gradients is not None:

                gradients = (

                    gradients

                    /

                    scaler.get_scale()

                )

        else:

            gradients = torch.autograd.grad(

                first_loss,

                features,

                retain_graph=True,

                create_graph=False,

                allow_unused=True

            )[0]


        if gradients is None:

            sensitivity = torch.ones(

                features.shape[0],

                features.shape[1],

                device=DEVICE

            )

        else:

            sensitivity = torch.sqrt(

                torch.mean(

                    gradients.detach() ** 2,

                    dim=2

                )

                +

                EPSILON

            )


        # ====================================================
        # SECOND FORWARD PASS
        # ====================================================

        with torch.autocast(

            device_type=DEVICE.type,

            dtype=torch.float16,

            enabled=USE_AMP

        ):

            output = model(

                rgb,

                depth,

                synthetic,

                sensitivity=sensitivity

            )


            logits = output[

                "logits"

            ]


            # Classification loss

            loss_cls = (

                classification_loss(

                    logits,

                    labels

                )

            )


            # Energy

            energy = output[

                "energy_distribution"

            ]


            # Target

            target = output[

                "target_distribution"

            ]


            # Redistribution loss

            loss_red = kl_divergence(

                target,

                energy

            )


            # Synthetic consistency

            synthetic_features = output[

                "synthetic_features"

            ]


            synthetic_energy = (

                model.calculate_energy_distribution(

                    synthetic_features

                )

            )


            loss_consistency = js_divergence(

                energy,

                synthetic_energy

            )


            # Entropy

            loss_entropy = entropy_regularization(

                target

            )


            # TOTAL LOSS

            loss = (

                loss_cls

                +

                LAMBDA_REDISTRIBUTION

                * loss_red

                +

                LAMBDA_CONSISTENCY

                * loss_consistency

                +

                LAMBDA_ENTROPY

                * loss_entropy

            )


        # ====================================================
        # BACKPROPAGATION
        # ====================================================

        if USE_AMP:

            scaler.scale(

                loss

            ).backward()


            scaler.unscale_(

                optimizer

            )


            torch.nn.utils.clip_grad_norm_(

                model.parameters(),

                1.0

            )


            scaler.step(

                optimizer

            )


            scaler.update()

        else:

            loss.backward()


            torch.nn.utils.clip_grad_norm_(

                model.parameters(),

                1.0

            )


            optimizer.step()


        # ====================================================
        # METRICS
        # ====================================================

        predictions = torch.argmax(

            logits,

            dim=1

        )


        correct = (

            predictions == labels

        ).sum().item()


        total_correct += correct

        total_samples += labels.size(0)


        total_loss += (

            loss.item()

            *

            labels.size(0)

        )


        progress.set_postfix(

            loss=(

                total_loss

                /

                total_samples

            ),

            accuracy=(

                total_correct

                /

                total_samples

            )

        )


    return (

        total_loss / total_samples,

        total_correct / total_samples

    )


