def create_pseudo_depth(
    image
):

    gray = ImageOps.grayscale(

        image

    )


    gray = gray.resize(

        (

            IMAGE_SIZE,

            IMAGE_SIZE

        )

    )


    gray = ImageEnhance.Contrast(

        gray

    ).enhance(

        1.5

    )


    depth = np.asarray(

        gray,

        dtype=np.float32

    ) / 255.0


    depth = torch.from_numpy(

        depth

    )


    depth = depth.unsqueeze(

        0

    )


    return depth


