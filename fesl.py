def create_pseudo_depth(image):

    """

    Creates a structural pseudo-depth representation.

    NOTE:
    This is NOT real depth sensor data.

    It is used to create a second structural modality
    for experimentation.

    """


    gray = ImageOps.grayscale(
        image
    )


    gray = gray.resize(

        (
            IMAGE_SIZE,

            IMAGE_SIZE

        )

    )


    gray = ImageEnhance.Contrast(

        gray

    ).enhance(

        1.5

    )


    depth = np.asarray(

        gray,

        dtype=np.float32

    )


    depth = (

        depth

        /

        255.0

    )


    depth = torch.from_numpy(
        depth
    )


    depth = depth.unsqueeze(
        0
    )


    return depth


