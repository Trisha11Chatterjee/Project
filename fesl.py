def create_synthetic_image(image):

    """

    Synthetic augmentation.

    NOTE:
    This is NOT a trained GAN.

    A real GAN generator can replace this function later.

    """


    img = image.copy()


    choice = random.randint(
        0,
        4
    )


    if choice == 0:

        img = ImageEnhance.Brightness(
            img
        ).enhance(

            random.uniform(
                0.75,
                1.25
            )

        )


    elif choice == 1:

        img = ImageEnhance.Contrast(
            img
        ).enhance(

            random.uniform(
                0.75,
                1.25
            )

        )


    elif choice == 2:

        img = ImageEnhance.Color(
            img
        ).enhance(

            random.uniform(
                0.70,
                1.30
            )

        )


    elif choice == 3:

        img = ImageOps.mirror(
            img
        )


    else:

        img = img.rotate(

            random.uniform(
                -15,
                15
            )

        )


    return img


