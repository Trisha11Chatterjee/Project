# ============================================================

class FESRViT(nn.Module):

    def __init__(

        self,

        num_classes=3,

        embed_dim=192,

        depth=6,

        heads=6

    ):

        super().__init__()


        self.embed_dim = embed_dim


        # --------------------------------------------
        # RGB branch
        # --------------------------------------------

        self.rgb_encoder = FeatureEncoder(

            3,

            embed_dim

        )


        # --------------------------------------------
        # Depth branch
        # --------------------------------------------

        self.depth_encoder = FeatureEncoder(

            1,

            embed_dim

        )


        # --------------------------------------------
        # Synthetic branch
        # --------------------------------------------

        self.synthetic_encoder = FeatureEncoder(

            3,

            embed_dim

        )


        # --------------------------------------------
        # Fusion
        # --------------------------------------------

        self.fusion = nn.Linear(

            embed_dim * 3,

            embed_dim

        )


        # --------------------------------------------
        # CLS token
        # --------------------------------------------

        self.cls_token = nn.Parameter(

            torch.zeros(

                1,

                1,

                embed_dim

            )

        )


        # Feature maps are 14 x 14 = 196 tokens
        # plus CLS token = 197

        self.position_embedding = nn.Parameter(

            torch.zeros(

                1,

                197,

                embed_dim

            )

        )


        # --------------------------------------------
        # Transformer
        # --------------------------------------------

        encoder_layer = nn.TransformerEncoderLayer(

            d_model=embed_dim,

            nhead=heads,

            dim_feedforward=embed_dim * 4,

            dropout=0.1,

            activation="gelu",

            batch_first=True,

            norm_first=True

        )


        self.transformer = nn.TransformerEncoder(

            encoder_layer,

            num_layers=depth

        )


        self.norm = nn.LayerNorm(

            embed_dim

        )


        # --------------------------------------------
        # Classifier
        # --------------------------------------------

        self.classifier = nn.Linear(

            embed_dim,

            num_classes

        )


        nn.init.trunc_normal_(

            self.cls_token,

            std=0.02

        )


        nn.init.trunc_normal_(

            self.position_embedding,

            std=0.02

        )


    # ========================================================
    # ENERGY
    # ========================================================

    def calculate_energy(

        self,

        features

    ):

        # F ∈ R^(B × N × D)

        energy = torch.mean(

            features ** 2,

            dim=1

        )


        return energy


    # ========================================================
    # ENERGY DISTRIBUTION
    # ========================================================

    def calculate_energy_distribution(

        self,

        features

    ):

        energy = self.calculate_energy(

            features

        )


        distribution = (

            energy

            /

            (

                energy.sum(

                    dim=1,

                    keepdim=True

                )

                + EPSILON

            )

        )


        return distribution


    # ========================================================
    # ENERGY-SENSITIVITY INTEGRATION
    # ========================================================

    def energy_sensitivity_integration(

        self,

        features,

        sensitivity

    ):

        energy = (

            self.calculate_energy_distribution(

                features

            )

        )


        sensitivity = (

            sensitivity

            /

            (

                sensitivity.sum(

                    dim=1,

                    keepdim=True

                )

                + EPSILON

            )

        )


        # ------------------------------------------------
        # Proposed integration
        #
        # T_j =
        #
        # (1-alpha) E_j
        # +
        # alpha S_j
        # ------------------------------------------------

        target = (

            (1.0 - ALPHA)

            *

            energy

            +

            ALPHA

            *

            sensitivity

        )


        target = target / (

            target.sum(

                dim=1,

                keepdim=True

            )

            + EPSILON

        )


        return (

            energy,

            sensitivity,

            target

        )


    # ========================================================
    # ADAPTIVE REDISTRIBUTION
    # ========================================================

    def adaptive_redistribution(

        self,

        features,

        sensitivity

    ):

        (

            energy,

            sensitivity_dist,

            target

        ) = self.energy_sensitivity_integration(

            features,

            sensitivity

        )


        # ------------------------------------------------
        # Mathematical redistribution
        #
        # w_j =
        #
        # sqrt(
        # T_j / E_j
        # )
        # ------------------------------------------------

        scale = torch.sqrt(

            (

                target

                +

                EPSILON

            )

            /

            (

                energy

                +

                EPSILON

            )

        )


        # Prevent numerical instability

        scale = torch.clamp(

            scale,

            min=0.25,

            max=4.0

        )


        balanced_features = (

            features

            *

            scale.unsqueeze(1)

        )


        return (

            balanced_features,

            energy,

            sensitivity_dist,

            target

        )


    # ========================================================
    # FORWARD
    # ========================================================

    def forward(

        self,

        rgb,

        depth,

        synthetic,

        sensitivity=None

    ):

        # ------------------------------------------------
        # Feature extraction
        # ------------------------------------------------

        F_R = self.rgb_encoder(
            rgb
        )


        F_D = self.depth_encoder(
            depth
        )


        F_S = self.synthetic_encoder(
            synthetic
        )


        # ------------------------------------------------
        # Token alignment
        # ------------------------------------------------

        n = min(

            F_R.shape[1],

            F_D.shape[1],

            F_S.shape[1]

        )


        F_R = F_R[
            :, :n, :
        ]


        F_D = F_D[
            :, :n, :
        ]


        F_S = F_S[
            :, :n, :
        ]


        # ------------------------------------------------
        # Feature fusion
        # ------------------------------------------------

        fused_features = torch.cat(

            [

                F_R,

                F_D,

                F_S

            ],

            dim=-1

        )


        fused_features = self.fusion(

            fused_features

        )


        # ------------------------------------------------
        # IMPORTANT FIX
        #
        # retain_grad() is called ONLY when:
        #
        # 1. Training
        # 2. Gradients enabled
        # 3. Tensor requires gradient
        # ------------------------------------------------

        if (

            self.training

            and

            torch.is_grad_enabled()

            and

            fused_features.requires_grad

        ):

            fused_features.retain_grad()


        # ------------------------------------------------
        # FESR redistribution
        # ------------------------------------------------

        if sensitivity is not None:

            (

                balanced_features,

                energy_distribution,

                sensitivity_distribution,

                target_distribution

            ) = self.adaptive_redistribution(

                fused_features,

                sensitivity

            )

        else:

            energy_distribution = (

                self.calculate_energy_distribution(

                    fused_features

                )

            )


            balanced_features = fused_features


            sensitivity_distribution = (
                energy_distribution
            )


            target_distribution = (
                energy_distribution
            )


        # ------------------------------------------------
        # CLS token
        # ------------------------------------------------

        B = balanced_features.shape[0]


        cls = self.cls_token.expand(

            B,

            -1,

            -1

        )


        tokens = torch.cat(

            [

                cls,

                balanced_features

            ],

            dim=1

        )


        # ------------------------------------------------
        # Position encoding
        # ------------------------------------------------

        tokens = (

            tokens

            +

            self.position_embedding[

                :, :tokens.shape[1], :

            ]

        )


        # ------------------------------------------------
        # ViT
        # ------------------------------------------------

        encoded = self.transformer(

            tokens

        )


        encoded = self.norm(

            encoded

        )


        # ------------------------------------------------
        # CLS representation
        # ------------------------------------------------

        representation = encoded[
            :,
            0
        ]


        # ------------------------------------------------
        # Classifier
        # ------------------------------------------------

        logits = self.classifier(

            representation

        )


        return {

            "logits":
                logits,

            "features":
                fused_features,

            "balanced_features":
                balanced_features,

            "energy_distribution":
                energy_distribution,

            "sensitivity_distribution":
                sensitivity_distribution,

            "target_distribution":
                target_distribution,

            "rgb_features":
                F_R,

            "depth_features":
                F_D,

            "synthetic_features":
                F_S,

            "representation":
                representation

        }


