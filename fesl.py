class PotatoDataset(Dataset):

    def __init__(

        self,

        paths,

        labels,

        transform

    ):

        self.paths = paths

        self.labels = labels

        self.transform = transform


    def __len__(self):

        return len(
            self.paths
        )


    def __getitem__(

        self,

        index

    ):

        path = self.paths[
            index
        ]

        label = self.labels[
            index
        ]


        image = Image.open(
            path
        ).convert(
            "RGB"
        )


        original = image.copy()


        # --------------------------------------------
        # RGB
        # --------------------------------------------

        rgb = self.transform(
            image
        )


        # --------------------------------------------
        # PSEUDO DEPTH
        # --------------------------------------------

        depth = create_pseudo_depth(
            original
        )


        # --------------------------------------------
        # SYNTHETIC
        # --------------------------------------------

        synthetic_image = (

            create_synthetic_image(
                original
            )

        )


        synthetic = self.transform(
            synthetic_image
        )


        return (

            rgb,

            depth,

            synthetic,

            torch.tensor(

                label,

                dtype=torch.long

            )

        )


