def calculate_task_sensitivity(

    features,

    loss

):

    """

    S_j = sqrt(
        mean(
            (dL/dF_j)^2
        )
    )

    """

    gradients = torch.autograd.grad(

        outputs=loss,

        inputs=features,

        retain_graph=True,

        create_graph=False,

        allow_unused=True

    )[0]


    if gradients is None:

        sensitivity = torch.ones(

            features.shape[0],

            features.shape[2],

            device=features.device

        )


    else:

        sensitivity = torch.sqrt(

            torch.mean(

                gradients.detach() ** 2,

                dim=1

            )

            +

            EPSILON

        )


    return sensitivity


