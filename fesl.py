# 23. FEATURE ENCODER
# ============================================================

class FeatureEncoder(
    nn.Module
):

    def __init__(

        self,

        input_channels,

        embed_dim=192

    ):

        super().__init__()


        self.encoder = nn.Sequential(

            nn.Conv2d(

                input_channels,

                64,

                kernel_size=3,

                stride=2,

                padding=1

            ),

            nn.BatchNorm2d(

                64

            ),

            nn.GELU(),


            nn.Conv2d(

                64,

                96,

                kernel_size=3,

                stride=2,

                padding=1

            ),

            nn.BatchNorm2d(

                96

            ),

            nn.GELU(),


            nn.Conv2d(

                96,

                128,

                kernel_size=3,

                stride=2,

                padding=1

            ),

            nn.BatchNorm2d(

                128

            ),

            nn.GELU(),


            nn.Conv2d(

                128,

                embed_dim,

                kernel_size=3,

                stride=2,

                padding=1

            ),

            nn.BatchNorm2d(

                embed_dim

            ),

            nn.GELU()

        )


    def forward(
        self,
        x
    ):

        x = self.encoder(

            x

        )


        x = x.flatten(

            2

        )


        x = x.transpose(

            1,

            2

        )


        return x


