def evaluate(loader):

    """

    Validation/test mode.

    IMPORTANT:
    No task-sensitivity gradient is calculated here.

    """

    model.eval()


    running_loss = 0.0

    running_total = 0


    all_labels = []

    all_predictions = []


    with torch.no_grad():

        progress = tqdm(

            loader,

            desc="Evaluation",

            leave=False

        )


        for (

            rgb,

            depth,

            synthetic,

            labels

        ) in progress:


            rgb = rgb.to(

                DEVICE,

                non_blocking=True

            )


            depth = depth.to(

                DEVICE,

                non_blocking=True

            )


            synthetic = synthetic.to(

                DEVICE,

                non_blocking=True

            )


            labels = labels.to(

                DEVICE,

                non_blocking=True

            )


            with torch.autocast(

                device_type=DEVICE.type,

                dtype=torch.float16,

                enabled=USE_AMP

            ):

                output = model(

                    rgb,

                    depth,

                    synthetic,

                    sensitivity=None

                )


                logits = output[
                    "logits"
                ]


                loss = classification_loss(

                    logits,

                    labels

                )


            running_loss += (

                loss.item()

                *

                labels.size(0)

            )


            running_total += labels.size(0)


            predictions = torch.argmax(

                logits,

                dim=1

            )


            all_labels.extend(

                labels.cpu().numpy()

            )


            all_predictions.extend(

                predictions.cpu().numpy()

            )


    epoch_loss = (

        running_loss

        /

        running_total

    )


    accuracy = accuracy_score(

        all_labels,

        all_predictions

    )


    precision = precision_score(

        all_labels,

        all_predictions,

        average="macro",

        zero_division=0

    )


    recall = recall_score(

        all_labels,

        all_predictions,

        average="macro",

        zero_division=0

    )


    f1 = f1_score(

        all_labels,

        all_predictions,

        average="macro",

        zero_division=0

    )


    return (

        epoch_loss,

        accuracy,

        precision,

        recall,

        f1,

        all_labels,

        all_predictions

    )


