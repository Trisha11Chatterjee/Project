# 33. EVALUATION
# ============================================================

def evaluate(

    loader

):

    model.eval()


    total_loss = 0.0

    total_samples = 0


    all_labels = []

    all_predictions = []


    # --------------------------------------------------------
    # IMPORTANT:
    #
    # Evaluation uses no gradients.
    # Therefore the model NEVER calls retain_grad()
    # because the forward function checks:
    #
    # self.training
    # torch.is_grad_enabled()
    # fused_features.requires_grad
    #
    # --------------------------------------------------------

    with torch.no_grad():

        for (

            rgb,

            depth,

            synthetic,

            labels

        ) in tqdm(

            loader,

            desc="Evaluation",

            leave=False

        ):


            rgb = rgb.to(

                DEVICE,

                non_blocking=True

            )


            depth = depth.to(

                DEVICE,

                non_blocking=True

            )


            synthetic = synthetic.to(

                DEVICE,

                non_blocking=True

            )


            labels = labels.to(

                DEVICE,

                non_blocking=True

            )


            with torch.autocast(

                device_type=DEVICE.type,

                dtype=torch.float16,

                enabled=USE_AMP

            ):

                output = model(

                    rgb,

                    depth,

                    synthetic,

                    sensitivity=None

                )


                logits = output[

                    "logits"

                ]


                loss = classification_loss(

                    logits,

                    labels

                )


            total_loss += (

                loss.item()

                *

                labels.size(0)

            )


            total_samples += labels.size(0)


            predictions = torch.argmax(

                logits,

                dim=1

            )


            all_labels.extend(

                labels.cpu().numpy()

            )


            all_predictions.extend(

                predictions.cpu().numpy()

            )


    avg_loss = (

        total_loss

        /

        total_samples

    )


    accuracy = accuracy_score(

        all_labels,

        all_predictions

    )


    precision = precision_score(

        all_labels,

        all_predictions,

        average="macro",

        zero_division=0

    )


    recall = recall_score(

        all_labels,

        all_predictions,

        average="macro",

        zero_division=0

    )


    f1 = f1_score(

        all_labels,

        all_predictions,

        average="macro",

        zero_division=0

    )


    return (

        avg_loss,

        accuracy,

        precision,

        recall,

        f1,

        all_labels,

        all_predictions

    )


