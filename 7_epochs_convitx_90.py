# 20. TRANSFORMER ENCODER BLOCK
# ================================================================

class TransformerEncoder(
    layers.Layer
):

    def __init__(

        self,

        projection_dim,

        num_heads,

        mlp_dim,

        dropout=0.1,

        **kwargs

    ):

        super().__init__(
            **kwargs
        )


        self.norm1 = (
            layers.LayerNormalization(
                epsilon=1e-6
            )
        )


        self.attention = (

            layers.MultiHeadAttention(

                num_heads=num_heads,

                key_dim=(
                    projection_dim //
                    num_heads
                ),

                dropout=dropout

            )

        )


        self.dropout1 = (
            layers.Dropout(
                dropout
            )
        )


        self.norm2 = (
            layers.LayerNormalization(
                epsilon=1e-6
            )
        )


        self.mlp = keras.Sequential(

            [

                layers.Dense(
                    mlp_dim,
                    activation=tf.nn.gelu
                ),

                layers.Dropout(
                    dropout
                ),

                layers.Dense(
                    projection_dim
                ),

                layers.Dropout(
                    dropout
                )

            ]

        )


    def call(
        self,
        inputs,
        training=False
    ):

        x = self.norm1(
            inputs
        )


        attention_output = (
            self.attention(

                x,
                x,

                training=training

            )
        )


        x = (

            inputs

            +

            self.dropout1(

                attention_output,

                training=training

            )

        )


        y = self.norm2(
            x
        )


        y = self.mlp(
            y,
            training=training
        )


        return x + y


