# 17. MOBILE NET V2 CNN BRANCH
# ================================================================

def build_cnn_branch(
    inputs
):

    # ------------------------------------------------------------
    # MobileNetV2 pretrained backbone
    # ------------------------------------------------------------

    base_model = (
        keras.applications.MobileNetV2(

            input_shape=(
                IMG_SIZE,
                IMG_SIZE,
                CHANNELS
            ),

            include_top=False,

            weights="imagenet"

        )
    )


    # ------------------------------------------------------------
    # Freeze initially
    # ------------------------------------------------------------

    base_model.trainable = False


    # ------------------------------------------------------------
    # We need the early MobileNetV2 feature representation.
    #
    # The paper specifies the first two blocks.
    # We identify the early feature tensor from MobileNetV2.
    # ------------------------------------------------------------

    x = base_model(
        inputs,
        training=False
    )


    # ------------------------------------------------------------
    # Reduce / refine CNN representation
    # ------------------------------------------------------------

    x = layers.Conv2D(

        48,

        kernel_size=1,

        padding="same",

        activation="relu"

    )(x)


    x = SEBlock(
        reduction=4,
        name="cnn_se"
    )(x)


    return x


