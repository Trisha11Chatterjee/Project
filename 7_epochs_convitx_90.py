# 19. PATCH ENCODER
# ================================================================

class PatchEncoder(
    layers.Layer
):

    def __init__(

        self,

        num_patches,

        projection_dim,

        **kwargs

    ):

        super().__init__(
            **kwargs
        )


        self.num_patches = (
            num_patches
        )


        self.projection = (
            layers.Dense(
                projection_dim
            )
        )


        self.position_embedding = (

            layers.Embedding(

                input_dim=
                num_patches,

                output_dim=
                projection_dim

            )

        )


    def call(
        self,
        patches
    ):

        positions = tf.range(

            start=0,

            limit=self.num_patches,

            delta=1

        )


        encoded = (

            self.projection(
                patches
            )

            +

            self.position_embedding(
                positions
            )

        )


        return encoded


