# 16. SE BLOCK
# ================================================================

class SEBlock(
    layers.Layer
):

    def __init__(
        self,
        reduction=4,
        **kwargs
    ):

        super().__init__(
            **kwargs
        )

        self.reduction = reduction

        self.gap = (
            layers.GlobalAveragePooling2D()
        )


    def build(
        self,
        input_shape
    ):

        channels = int(
            input_shape[-1]
        )

        reduced_channels = max(
            channels //
            self.reduction,
            1
        )


        self.fc1 = layers.Dense(

            reduced_channels,

            activation="relu"

        )


        self.fc2 = layers.Dense(

            channels,

            activation="sigmoid"

        )


    def call(
        self,
        inputs
    ):

        squeeze = self.gap(
            inputs
        )


        excitation = self.fc1(
            squeeze
        )


        excitation = self.fc2(
            excitation
        )


        excitation = tf.reshape(

            excitation,

            [
                tf.shape(inputs)[0],
                1,
                1,
                tf.shape(inputs)[-1]
            ]

        )


        return inputs * excitation


